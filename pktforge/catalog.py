"""The device catalogue: every model pktforge can place, what Packet Tracer made of it, and how to cable it.

`entries()` is the data (also behind `pktforge catalog --json`); `markdown()` renders the human/agent report that
ships as pktforge/data/DEVICES.md.
"""
import re

import pktforge
from pktforge import build, ports
import lab_api

PALETTE = {                      # what Packet Tracer's device palette calls each class of device
    "router": "Network Devices > Routers",
    "switch": "Network Devices > Switches",
    "multilayer-switch": "Network Devices > Switches",
    "firewall": "Network Devices > Security",
    "access-point": "Network Devices > Wireless Devices",
    "pc": "End Devices",
    "laptop": "End Devices",
    "server": "End Devices",
    "sniffer": "End Devices",
    "iot": "End Devices > Home / Industrial IoT",
    "pdd": "Components",
    "default": "Other",
}


def compress(names):
    """['FastEthernet0/1', ..., 'FastEthernet0/24'] -> 'FastEthernet0/1-24'"""
    out, i = [], 0
    while i < len(names):
        m = re.match(r"^(.*?)(\d+)$", names[i])
        if not m:
            out.append(names[i])
            i += 1
            continue
        j = i
        while j + 1 < len(names):
            n = re.match(r"^(.*?)(\d+)$", names[j + 1])
            if not n or n.group(1) != m.group(1) or int(n.group(2)) != int(re.match(r"^(.*?)(\d+)$", names[j]).group(2)) + 1:
                break
            j += 1
        if j > i:
            out.append("%s%s-%s" % (m.group(1), m.group(2), re.match(r"^(.*?)(\d+)$", names[j]).group(2)))
        else:
            out.append(names[i])
        i = j + 1
    return out


def status(model):
    if model in ports.REJECTED:
        return "rejected"
    if model in ports.TRAFFIC_VERIFIED:
        return "traffic-verified"
    if model in ports.VERIFIED_MODELS:
        return "ports-verified"
    return "untested"


KIND_OVERRIDES = {"LAP-PT": "access-point"}     # pktforge's name heuristic says laptop; PT's palette says wireless AP


def kind_of(model):
    return KIND_OVERRIDES.get(model) or lab_api.kind_for_model(model)


def entries():
    models, modules = build._templates()
    help_ = build._pt_help()
    out = []
    for m in sorted(models, key=lambda s: (kind_of(s), s.lower())):
        kind = kind_of(m)
        try:
            names = build.model_ports(m)
        except Exception:
            names = []
        fiber = set(ports.FIBER_PORTS.get(m, ()))
        out.append({
            "model": m,
            "kind": kind,
            "palette": PALETTE.get(kind, "Other"),
            "status": status(m),
            "ports": names,
            "fiber_ports": sorted(fiber),
            "modules": help_.get(m, {}).get("modules", []),
            "in_pt_help": m in help_,
            "note": ports.REJECTED.get(m, ""),
        })
    return out


STATUS_TEXT = {
    "traffic-verified": "Traffic passed in Packet Tracer 9.0.1. Safe default.",
    "ports-verified": "Opens in Packet Tracer 9.0.1 and keeps its cables under the names listed. No traffic test yet.",
    "untested": "A template exists but was never opened in Packet Tracer by pktforge. Check the result by hand.",
    "rejected": "Packet Tracer 9.0.1 refuses to open a file containing it. pktforge will not build it; add it by hand.",
}


def markdown():
    es = entries()
    models, _ = build._templates()
    lines = ["# Device catalogue", "",
             "Generated by `pktforge catalog --md` from the bundled templates, `pktforge/data/census.json` (what Packet "
             "Tracer %s did with each model) and `pktforge/data/pt_help.json` (module compatibility from Packet "
             "Tracer's own help). Do not edit by hand." % pktforge_pt(), "",
             "Use the **model** column as `\"model\"` in a spec and the **ports** column in `links`. "
             "Abbreviations (`Gi0/0`, `Fa0`, `Se0/0/0`) are accepted.", ""]
    counts = {}
    for e in es:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    lines += ["| status | models | meaning |", "|---|---|---|"]
    for s in ("traffic-verified", "ports-verified", "untested", "rejected"):
        lines.append("| %s | %d | %s |" % (s, counts.get(s, 0), STATUS_TEXT[s]))
    lines.append("")

    order = [("router", "Routers"), ("switch", "Switches"), ("multilayer-switch", "Multilayer switches"),
             ("firewall", "Firewalls"), ("pc", "PCs and phones"), ("laptop", "Laptops"), ("server", "Servers"),
             ("sniffer", "Sniffers"), ("access-point", "Access points")]
    for kind, title in order:
        rows = [e for e in es if e["kind"] == kind]
        if not rows:
            continue
        lines += ["## %s" % title, "", "Packet Tracer palette: %s" % rows[0]["palette"], "",
                  "| model | status | ports | modules PT's help allows | notes |", "|---|---|---|---|---|"]
        for e in rows:
            note = []
            if e["fiber_ports"]:
                note.append("fibre (no copper cable): " + ", ".join(e["fiber_ports"]))
            if e["note"]:
                note.append(e["note"])
            if not e["ports"]:
                note.append("no known port names")
            ps = ", ".join(compress(e["ports"])) or "-"
            lines.append("| `%s` | %s | %s | %s | %s |" % (e["model"], e["status"], ps,
                                                        ", ".join(e["modules"]) or "-", "; ".join(note)))
        lines.append("")
    lines += palette_section(models)
    other = [e for e in es if e["kind"] not in {k for k, _ in order}]
    lines += ["## Everything else", "",
              "%d more templates (IoT sensors, appliances, VoIP, cloud...). They build, but pktforge has not opened "
              "them in Packet Tracer; run `pktforge models` to list them." % len(other), ""]
    help_ = build._pt_help()
    missing = sorted(n for n in help_ if n not in models)
    if missing:
        lines += ["## In Packet Tracer's palette but with no pktforge template", "",
                  ", ".join("`%s`" % n for n in missing) + ".", "",
                  "Add these by hand in Packet Tracer after opening the generated file.", ""]
    lines += ["## Port-name facts worth knowing", "",
              "* Routers: `GigabitEthernet0/0` on 1941/2901/2911; `GigabitEthernet0/0/0` on ISR4321/ISR4331; "
              "`FastEthernet0/0` on 1841/2811/2620XM/2621XM; `FastEthernet0/0`, `1/0`, `Serial2/0`... on Router-PT.",
              "* Switches: `FastEthernet0/1-24` + `GigabitEthernet0/1-2` on 2960-24TT/2950T-24/3560-24PS; "
              "`GigabitEthernet1/0/1-28` on 3650-24PS and IE-9320; `FastEthernet0/1`, `1/1`, `2/1`... on Switch-PT.",
              "* End devices: `FastEthernet0` on PC-PT, Server-PT and Laptop-PT.",
              "* A port Packet Tracer calls fibre cannot take a copper cable; pktforge rejects such a link (E009).",
              "* `Serial0/0/0` and `Serial0/0/1` appear on a router after `\"modules\": [\"HWIC-2T\"]`.",
              "* Packet Tracer adds a `Power Distribution Device0` to every lab it saves; that is normal.", ""]
    return "\n".join(lines)


def palette_section(models):
    import json
    import os
    with open(os.path.join(pktforge.DATA_DIR, "palette.json"), encoding="utf-8") as fh:
        pal = json.load(fh)
    lines = ["## Packet Tracer palette map", "",
             "What the on-screen palette calls each device, and the pktforge `model` for it (`-` = no template, so "
             "add it by hand in Packet Tracer). Top-level groups in the palette: %s." % ", ".join(pal["groups"]), ""]
    for group, subs in pal["sections"].items():
        for sub, items in subs.items():
            lines += ["**%s > %s**" % (group, sub), "", "| palette label | pktforge model | status |", "|---|---|---|"]
            for label, model in items:
                if model and model in models:
                    lines.append("| %s | `%s` | %s |" % (label, model, status(model)))
                else:
                    lines.append("| %s | - | no template |" % label)
            lines.append("")
    lines += ["_%s_" % pal["unread"], ""]
    return lines


def pktforge_pt():
    import json
    import os
    with open(os.path.join(pktforge.DATA_DIR, "census.json"), encoding="utf-8") as fh:
        return json.load(fh)["packet_tracer"]
